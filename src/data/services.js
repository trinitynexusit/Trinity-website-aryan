export const getFeaturedServices = (limit = 8) => {
    const featured = [];
    const domainMap = {};
    services.forEach((service) => {
        if (!domainMap[service.domain]) {
            domainMap[service.domain] = [];
        }
        domainMap[service.domain].push(service);
    });
    Object.values(domainMap).forEach((domainServices) => {
        if (featured.length < limit) {
            featured.push(domainServices[0]);
        }
    });
    services.forEach((service) => {
        if (featured.length < limit && !featured.includes(service)) {
            featured.push(service);
        }
    });
    return featured.slice(0, limit);
};
